"""Generated summaries must remain tied to the measured negative result."""
import importlib.util
import json
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('shell_docs_test', ROOT/'scripts/49_sync_shell_docs.py')
shell = importlib.util.module_from_spec(spec)
spec.loader.exec_module(shell)


def fixture(root):
    for name in (shell.REPORT, shell.CALIBRATION):
        path = root/name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes((ROOT/name).read_bytes())
    for name in ('README.md','README.zh-CN.md','docs/ARCHITECTURE.md','docs/TRANSFER.md','docs/CLAIMS.md'):
        (root/name).parent.mkdir(parents=True,exist_ok=True)
        (root/name).write_text('# Reference\n\n## English\n\n## 简体中文\n',encoding='utf-8')
    (root/'docs/SAFETY_SHELL.md').write_text('scope',encoding='utf-8')
    (root/'docs/claims.json').write_text('{"claims":[]}',encoding='utf-8')
    shell.sync(root)


def test_generated_shell_is_idempotent_and_preserves_negative_acceptance(tmp_path):
    fixture(tmp_path)
    before = {name:(tmp_path/name).read_bytes() for name in shell.documents(tmp_path)}
    shell.sync(tmp_path)
    assert before == {name:(tmp_path/name).read_bytes() for name in before}
    assert shell.check(tmp_path)['ok']
    assert 'negative_stop' in (tmp_path/'README.md').read_text(encoding='utf-8')


def test_new_prose_change_fails_without_changing_the_data(tmp_path):
    fixture(tmp_path)
    path = tmp_path/'docs/TRANSFER.md'
    path.write_text(path.read_text(encoding='utf-8').replace('negative_stop','passed'),encoding='utf-8')
    with pytest.raises(AssertionError,match='Stale shell summary'):
        shell.check(tmp_path)


def test_source_accounting_drift_is_detected(tmp_path):
    fixture(tmp_path)
    path = tmp_path/shell.REPORT
    data = json.loads(path.read_text(encoding='utf-8'))
    data['accounting']['actual_objective_evaluations'] += 1
    path.write_text(json.dumps(data),encoding='utf-8')
    with pytest.raises(AssertionError,match='Stale shell summary'):
        shell.check(tmp_path)


def test_sync_normalizes_all_owned_table_markers_and_real_claim_evaluator_passes(tmp_path, monkeypatch):
    fixture(tmp_path)
    claims = shell.registered(tmp_path)
    path = tmp_path/'docs/CLAIMS.md'
    # Simulate both bilingual tables left by 23_sync_reference_docs, alongside
    # the correctly formatted summary markers already generated by this script.
    stale_tables = '\n'.join(
        f"| {claim['id']} | <!-- claim:{claim['id']} -->{claim['value']:.6f}<!-- /claim --> |"
        for _ in ('en', 'zh') for claim in claims)
    path.write_text(path.read_text(encoding='utf-8')+'\n'+stale_tables+'\n', encoding='utf-8')
    evaluator_spec = importlib.util.spec_from_file_location(
        'shell_docs_real_claim_evaluator', ROOT/'scripts/16_check_claims.py')
    evaluator = importlib.util.module_from_spec(evaluator_spec)
    evaluator_spec.loader.exec_module(evaluator)
    monkeypatch.setattr(evaluator, 'ROOT', tmp_path)
    assert all(evaluator.evaluate(claim)[0] is False for claim in claims)
    source_before = (tmp_path/shell.REPORT).read_bytes()
    shell.sync(tmp_path)
    assert all(evaluator.evaluate(claim)[0] is True for claim in claims)
    assert (tmp_path/shell.REPORT).read_bytes() == source_before
    assert shell.check(tmp_path)['ok']
    body = path.read_text(encoding='utf-8')
    for claim in claims:
        rendered = format(claim['value'], claim['documents'][0]['format'])
        expected = f"<!-- claim:{claim['id']} -->{rendered}<!-- /claim -->"
        assert body.count(expected) == 4  # Two summaries and two table rows.
